export function workflowIndexForPhase(phase: string): number {
  switch (phase) {
    case 'created':
    case 'preparing':
      return 0;
    case 'running':
      return 1;
    case 'detecting':
      return 3;
    case 'investigating':
      return 3;
    case 'responding':
      return 4;
    case 'containing':
      return 5;
    case 'evaluating':
      return 6;
    case 'completed':
      return 6;
    default:
      return 0;
  }
}
